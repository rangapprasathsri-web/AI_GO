"""
Tests for LiveImageAdapter.

Verifies:
- OpenAI DALL-E tier mapping (Economy: dall-e-2 256x256; Standard: dall-e-3 standard; Maximum: dall-e-3 hd).
- Environment provider selection (OpenAI vs Diffusion vs Demo).
- Per-session budget cap enforcement (falls back cleanly after cap).
- Request timeout and error fallback (zero crashes).
- Strict secret isolation (API key never exposed in output or metadata).
- Tests never make paid external calls (all mocked).
"""
import base64
import io
import pytest
from unittest.mock import patch, MagicMock
from PIL import Image

from backend.adapters.live_image_adapter import LiveImageAdapter
from backend.engine.models import StrategyConfig, UserRequest


def create_sample_b64_image() -> str:
    """Create a 10x10 PNG encoded as base64."""
    img = Image.new("RGB", (10, 10), color="blue")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode("utf-8")


@pytest.fixture
def dummy_request():
    return UserRequest(
        id="test-req-1",
        prompt="A cute cartoon kitten playing with wool",
        domain="image_resource_optimizer",
        inputs={"_category": "coloring_sheet"},
    )


def test_openai_tier_mapping_and_controls(dummy_request):
    adapter = LiveImageAdapter(openai_api_key="sk-test-secret-key-12345", real_generation_cap=10)
    assert adapter.mode == "openai"
    assert adapter.is_real is True

    fake_b64 = create_sample_b64_image()
    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {"data": [{"b64_json": fake_b64}]}

    # 1. Economy Tier -> DALL-E 2 256x256
    with patch("requests.post", return_value=mock_resp) as mock_post:
        strat = StrategyConfig(name="economy", adapter="mock_image", price_per_call=0.016, params={"width": 256, "height": 256})
        res = adapter.execute(strat, dummy_request)

        assert res.success is True
        assert res.actual_cost == 0.016
        assert res.metadata["model"] == "dall-e-2"
        assert res.metadata["size"] == "256x256"
        assert res.metadata["is_placeholder"] is False
        assert "Generated by OpenAI dall-e-2" in res.metadata["placeholder_label"]
        # Verify secret key is not in metadata or reference
        assert "sk-test-secret-key-12345" not in str(res.metadata)
        assert "sk-test-secret-key-12345" not in res.output_reference

        # Verify payload sent to OpenAI
        call_kwargs = mock_post.call_args[1]
        assert call_kwargs["json"]["model"] == "dall-e-2"
        assert call_kwargs["json"]["size"] == "256x256"

    # 2. Maximum Tier -> DALL-E 3 1024x1024 HD
    with patch("requests.post", return_value=mock_resp) as mock_post:
        strat = StrategyConfig(name="maximum", adapter="mock_image", price_per_call=0.080, params={"width": 1024, "height": 1024})
        res = adapter.execute(strat, dummy_request)

        assert res.success is True
        assert res.actual_cost == 0.080
        assert res.metadata["model"] == "dall-e-3"
        assert res.metadata["quality"] == "hd"

        call_kwargs = mock_post.call_args[1]
        assert call_kwargs["json"]["model"] == "dall-e-3"
        assert call_kwargs["json"]["quality"] == "hd"


def test_session_budget_cap_enforcement(dummy_request):
    adapter = LiveImageAdapter(openai_api_key="sk-test-key", real_generation_cap=2)
    fake_b64 = create_sample_b64_image()
    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {"data": [{"b64_json": fake_b64}]}

    with patch("requests.post", return_value=mock_resp):
        strat = StrategyConfig(name="economy", adapter="mock_image", price_per_call=0.01)

        # Call 1: Real
        r1 = adapter.execute(strat, dummy_request)
        assert r1.metadata["is_placeholder"] is False
        assert adapter.real_generations_count == 1

        # Call 2: Real
        r2 = adapter.execute(strat, dummy_request)
        assert r2.metadata["is_placeholder"] is False
        assert adapter.real_generations_count == 2

        # Call 3: Exceeds cap (2) -> Falls back cleanly to demo mock
        r3 = adapter.execute(strat, dummy_request)
        assert r3.success is True
        assert r3.metadata["is_placeholder"] is True
        assert "Budget cap" in r3.metadata.get("fallback_notice", "")
        # Real count should remain capped at 2
        assert adapter.real_generations_count == 2


def test_graceful_fallback_on_network_timeout(dummy_request):
    adapter = LiveImageAdapter(openai_api_key="sk-test-key", real_generation_cap=10, enable_live_diffusion=False)

    # Simulate timeout
    with patch("requests.post", side_effect=Exception("Connection timed out")):
        strat = StrategyConfig(name="standard", adapter="mock_image", price_per_call=0.04)
        # Must not raise an exception; must gracefully fall back
        res = adapter.execute(strat, dummy_request)
        assert res.success is True
        # Falls back to demo mock
        assert res.metadata["is_placeholder"] is True
        assert "OpenAI generation failed" in res.metadata.get("fallback_notice", "")
